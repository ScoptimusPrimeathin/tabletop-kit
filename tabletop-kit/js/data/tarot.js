// ---------- build the final list ----------
export const TAROT = [];
MAJORS.forEach(([name, up, rev, upText, revText], i) => {
  TAROT.push({ id: `M${i}`, name, arcana: 'major', suit: null, rank: i, up, rev, upText, revText });
});
for (const suit of Object.keys(MINORS)) {
  MINORS[suit].forEach(([rank, up, rev, upText, revText]) => {
    TAROT.push({ id: `${suit[0]}${rank}`, name: `${rank} of ${suit}`, arcana: 'minor', suit, rank, up, rev, upText, revText });
  });
}

export const TAROT_BY_ID = Object.fromEntries(TAROT.map((c) => [c.id, c]));

